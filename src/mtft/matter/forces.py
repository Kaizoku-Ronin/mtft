def unit_norm(D):
    """Norm of the fundamental unit of the order of discriminant D > 0: -1 iff x^2 - D y^2 = -4 has a solution (searched; D small)."""
    for yv in range(1, 10000):
        for sgn in (-4, 4):
            xx = D * yv * yv + sgn
            if xx > 0 and int(math.isqrt(xx)) ** 2 == xx:
                return -1 if sgn == -4 else 1
    return None


def reversibility():
    """The golden loop is reversed inside SL(2,Z) by the half-turn S at i (S M S^-1 = M^-1, phi of norm -1); the twelve loop is not: no element
    with entries up to 8 conjugates it to its inverse, and x^2 - 3 y^2 = -1 is impossible mod 3 (2 + sqrt 3 of norm +1), so its two directions are
    different closed loops of X(1), exchanged only by a mirror (time reversal)."""
    Mg, M12 = sp.Matrix(GOLDEN), sp.Matrix(TWELVE)
    s_reverses = S_MAT * Mg * S_MAT.inv() == Mg.inv()
    found = []
    for g in itertools.product(range(-8, 9), repeat=4):
        if g[0] * g[3] - g[1] * g[2] == 1:
            G = sp.Matrix([[g[0], g[1]], [g[2], g[3]]])
            if G * M12 * G.inv() == M12.inv():
                found.append(g)
    mod3 = any((xv * xv - 3 * yv * yv + 1) % 3 == 0 for xv in range(3) for yv in range(3))
    return {"golden": {"S_reverses": s_reverses, "unit_norm": unit_norm(5)}, "twelve": {"conjugators_up_to_8": found, "minus_one_norm_mod_3": mod3, "unit_norm": unit_norm(12)},
            "reading": "norm -1: the loop is its own reverse up to a rotation; norm +1: only a reflection reverses it"}


def icosahedron():
    """X(5) is the icosahedron: index 60, twelve cusps at the vertices (0, +-1, +-phi), 30 half-turn points at the edges, 20 third-turn points at
    the faces, genus 0 — the one place twelve and phi meet exactly in the modular world (level 5, not 143)."""
    mu = 60; c = mu // 5
    g = 1 + Fr(mu, 12) - Fr(c, 2)
    return {"index": mu, "cusps": c, "order_2": mu // 2, "order_3": mu // 3, "genus": g, "vertices": "(0, +-1, +-phi) and cyclic permutations",
            "euler": c - mu // 2 + mu // 3}


