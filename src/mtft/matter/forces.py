def singlet_blocks(parent, y=None):
    out = []
    for b in menu(parent):
        r = rep(b["q"], y, b["k"])
        if r["colour"] == "1" and r["weak"] == 1 and r["Y"] == 0 and any(b["q"]):
            out.append(b)
    return out


def touch_scan(parent, y=None):
    """Every SM-singlet block of the parent's menu and the fields it reaches at first order; the sealed rule PR-S3."""
    F = field_vectors(); rows = []
    for b in singlet_blocks(parent, y):
        reach = {f: dot(b["q"], v) for f, v in F.items()}
        rows.append({"block": b["name"], "kind": b["kind"], "q": tuple(str(x) for x in b["q"]), "touch": {f: str(t) for f, t in reach.items()}, "reaches": [f for f, t in reach.items() if t],
                     "down_sector": bool(reach["d^c"] or reach["H_d"])})
    return {"parent": parent, "singlets": rows, "reaches_down_sector": any(r["down_sector"] for r in rows),
            "verdict": "PASS" if any(r["down_sector"] for r in rows) else "FAIL"}


def touch_test(parent):
    """The sealed evaluation (PR-S3): PASS iff the parent's menu has an SM-singlet block that reaches the down sector."""
    s = touch_scan(parent)
    return {"parent": parent, "verdict": s["verdict"], "blocks_reaching_down": [r["block"] for r in s["singlets"] if r["down_sector"]],
            "singlet_blocks": [r["block"] for r in s["singlets"]]}


