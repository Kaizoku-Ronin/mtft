def anomaly_free_space():
    """Route A, step 1.  Stack hypercharges y (y_L = 0 fixes the shift that no difference line sees) such that one generation of lines
    (Q, u^c, d^c, L, e^c, nu^c) is anomaly-free: SU(3)^2 Y, SU(2)^2 Y, grav^2 Y and Y^3.  Returns the solution space (EXACT)."""
    yc, yA1, yB, yA2 = sp.symbols("y_c y_A1 y_B y_A2")
    y = {"c": yc, "A1": yA1, "L": 0, "B": yB, "A2": yA2}
    Y = {f: y[i] - y[j] for f, (i, j) in FIELDS.items()}
    eqs = [2 * Y["Q"] + Y["u^c"] + Y["d^c"],                                                   # SU(3)^2 Y
           3 * Y["Q"] + Y["L"],                                                                 # SU(2)^2 Y
           6 * Y["Q"] + 3 * Y["u^c"] + 3 * Y["d^c"] + 2 * Y["L"] + Y["e^c"] + Y["nu^c"],        # grav^2 Y
           6 * Y["Q"] ** 3 + 3 * Y["u^c"] ** 3 + 3 * Y["d^c"] ** 3 + 2 * Y["L"] ** 3 + Y["e^c"] ** 3 + Y["nu^c"] ** 3]   # Y^3
    sol = sp.solve([sp.expand(q) for q in eqs], [yA1, yB, yA2], dict=True)
    gens = {"T_3R": {s: T3R[s] for s in STACKS}, "(B-L)/2": {s: BML[s] / 2 for s in STACKS}}
    return {"solutions": sol, "free_symbols": sorted({str(s) for d in sol for v in d.values() for s in v.free_symbols} | {str(yc)}),
            "dimension": 2, "generators": gens, "equations": [str(sp.expand(q)) for q in eqs]}


def hypercharge_route_a():
    """Route A: anomalies leave <T_3R, B - L>; Y(Q) = 1/6 fixes the B - L coefficient; a neutral Higgs component (the photon survives) fixes the
    T_3R coefficient a to +-1 (a = 3 would also pass Z6 and the anomalies); a = -1 is the u <-> d relabelling (B <-> A2)."""
    a = sp.Symbol("a")
    y = {s: a * T3R[s] + BML[s] / 2 for s in STACKS}                                     # the anomaly-free family through Y(Q) = 1/6
    Yf = {f: sp.nsimplify(y[i] - y[j]) for f, (i, j) in FIELDS.items()}
    sols = sorted({int(v) for target in (sp.Rational(1, 2), sp.Rational(-1, 2)) for v in sp.solve(sp.Eq(Yf["H_u"], target), a)})
    z6_odd = []
    for k in range(-5, 6):
        yk = {s: Fr(k) * T3R[s] + BML[s] / 2 for s in STACKS}
        if all(z6_phase(rep(line(i, j), yk)) == 0 for (i, j) in FIELDS.values()):
            z6_odd.append(k)
    out = {}
    for k in sols:
        yk = {s: Fr(int(k)) * T3R[s] + BML[s] / 2 for s in STACKS}
        out[int(k)] = {"y": yk, "fields": {f: rep(v, yk)["Y"] for f, v in field_vectors().items()}}
    return {"family": {s: str(y[s]) for s in STACKS}, "higgs_Y": str(Yf["H_u"]), "neutral_higgs_solutions": sols, "z6_passes_for_a_in": z6_odd,
            "assignments": out, "standard": out[1]["y"] == Y_STACK, "swap_is_relabelling": out[-1]["y"] == {**Y_STACK, "B": Y_STACK["A2"], "A2": Y_STACK["B"]}}


def hypercharge_route_b():
    """Route B: the Pati–Salam embedding, Y = T_3R + (B - L)/2 (PS-01), with the Pythagorean normalisation (B - L)/2 = sqrt(2/3) T_15."""
    y = {s: T3R[s] + BML[s] / 2 for s in STACKS}
    import numpy as np
    T15 = np.diag([1, 1, 1, -3]) / (2 * math.sqrt(6)); BL2 = np.diag([1 / 6, 1 / 6, 1 / 6, -1 / 2])
    c = float((BL2 @ T15).trace() / (T15 @ T15).trace())
    return {"y": y, "equals_standard": y == Y_STACK, "bml_over_t15": c, "c_squared": c * c, "two_thirds": abs(c * c - 2 / 3) < 1e-12}


def hypercharge_e2():
    a, b = hypercharge_route_a(), hypercharge_route_b()
    return {"route_a": a["assignments"][1]["y"], "route_b": b["y"], "agree": a["assignments"][1]["y"] == b["y"] == Y_STACK,
            "note": "two routes: anomalies + normalisation + a neutral Higgs component; the Pati–Salam embedding"}


