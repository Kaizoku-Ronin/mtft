STACKS = ("c", "A1", "L", "B", "A2")                      # the Standard-Model grouping of the eight dots: U(3) x U(1) x U(2) x U(1) x U(1)
RANK = {"c": 3, "A1": 1, "L": 2, "B": 1, "A2": 1}
