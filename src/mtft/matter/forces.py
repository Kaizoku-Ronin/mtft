def e(stack):
    return tuple(1 if s == stack else 0 for s in STACKS)


def vec(*pairs):
    """Charge vector from (stack, charge) pairs."""
    v = [0] * len(STACKS)
    for s, q in pairs:
        v[STACKS.index(s)] += q
    return tuple(v)


def line(i, j):
    """The difference line e_i - e_j = Hom(j -> i)."""
    return vec((i, 1), (j, -1))


def field_vectors():
    return {f: line(i, j) for f, (i, j) in FIELDS.items()}


def carriers(grouping):
    """Force carriers of a grouping: the circles (one per dot) and the lines inside each group — dim of prod U(n_i)."""
    n = list(grouping.values())
    return {"circles": sum(n), "lines_inside": sum(k * (k - 1) for k in n), "total": sum(k * k for k in n),
            "weyl_order": math.prod(math.factorial(k) for k in n), "nonabelian_dim": sum(k * k - 1 for k in n)}


def particle_lines(grouping):
    """Lines between groups (both orientations) and the total U(8) adjoint count 64 = carriers + lines between."""
    n = list(grouping.values())
    between = sum(2 * a * b for a, b in itertools.combinations(n, 2))
    return {"lines_between": between, "states": between, "check_64": sum(k * k for k in n) + between == 64}


def partitions_of_eight():
    """The 22 ways to group eight dots into forces (partitions of 8)."""
    out = []

    def rec(rest, mx, cur):
        if rest == 0:
            out.append(tuple(cur)); return
        for k in range(min(rest, mx), 0, -1):
            rec(rest - k, k, cur + [k])
    rec(8, 8, [])
    return out


def sheet_blocks(k, grouping=None):
    """Blocks of Lambda^k(8) under the grouping: multiplicities (k_s) with k_s <= n_s and sum k; dimension prod C(n_s, k_s)."""
    g = grouping or RANK; names = list(g)
    out = []
    for ks in itertools.product(*[range(g[s] + 1) for s in names]):
        if sum(ks) == k:
            out.append({"k": tuple(ks), "dim": math.prod(math.comb(g[s], kk) for s, kk in zip(names, ks))})
    assert sum(b["dim"] for b in out) == math.comb(8, k)
    return out


def _name(k):
    return "+".join(s for s, kk in zip(STACKS, k) for _ in range(kk)) or "1"


def menu(parent):
    """The block menu of a parent, one block per conjugate pair (a block and its conjugate are one field), each with its charge vector q in the
    five stack U(1)s (the line bundle: chirality and hypercharge are linear in q), its multiplicities k (the SU(3) x SU(2) representation) and its
    dimension.
    'U8'   difference lines e_i - e_j (the adjoint of U(8): every field a U(8)-adjoint block — the supersymmetric reading), one per unordered pair;
    'SO16' + the sum lines e_i + e_j, the 28 blocks of Lambda^2(8) (their conjugates are the other 28 roots of SO(16));
    'E8'   + the 128 even sheets, the spinor of SO(16): Lambda^k(8) (x) det^{-1/2} for even k, charge k_s - n_s/2 on stack s (half-integers: the
           flux must lift to Spin(16)), one block per +- pair of multiplicity patterns (24 blocks, 64 states)."""
    blocks = []
    for i, j in itertools.combinations(STACKS, 2):
        q = line(i, j); blocks.append({"q": q, "k": q, "kind": "difference", "dim": RANK[i] * RANK[j], "name": f"{i}<-{j}"})
    if parent == "U8":
        return blocks
    for b in sheet_blocks(2):
        if b["dim"]:
            blocks.append({"q": tuple(Fr(x) for x in b["k"]), "k": b["k"], "kind": "sum", "dim": b["dim"], "name": _name(b["k"])})
    if parent == "SO16":
        return blocks
    for k in (0, 2, 4, 6, 8):
        for b in sheet_blocks(k):
            if not b["dim"]:
                continue
            q = tuple(Fr(kk) - Fr(RANK[s], 2) for s, kk in zip(STACKS, b["k"]))
            if q > tuple(-x for x in q):                                   # one of each conjugate pair
                blocks.append({"q": q, "k": b["k"], "kind": f"sheet{k}", "dim": b["dim"], "name": "spinor " + _name(b["k"])})
    return blocks


def colour_rep(k):
    """SU(3) representation of a colour multiplicity (difference lines: +-1; sheets: 0..3)."""
    return {0: "1", 1: "3", 2: "3bar", 3: "1", -1: "3bar"}[k]


def rep(q, y=None, k=None):
    """SM representation of a block: colour from the colour multiplicity (+-1 for lines, 0..3 for sheets), weak dimension, hypercharge sum q_s y_s,
    triality and duality.  k defaults to q (difference lines and sum lines)."""
    y = y or Y_STACK; k = k if k is not None else q
    kc, kA1, kL, kB, kA2 = (int(x) for x in k)
    col = colour_rep(kc); t = kc % 3
    weak = 2 if kL in (1, -1) else 1; d = kL % 2
    Y = sum(Fr(qs) * y[s] for qs, s in zip(q, STACKS))
    return {"colour": col, "weak": weak, "Y": Y, "triality": t, "duality": d}


def conjugate_rep(r):
    return {"colour": {"1": "1", "3": "3bar", "3bar": "3"}[r["colour"]], "weak": r["weak"], "Y": -r["Y"],
            "triality": (-r["triality"]) % 3, "duality": r["duality"]}


def rep_key(r):
    return (r["colour"], r["weak"], r["Y"])


def sm_table(y=None):
    """The Standard-Model fields as lines with their representations (PS-01's branching)."""
    out = {}
    for f, v in field_vectors().items():
        r = rep(v, y); out[f] = {"q": v, **r}
    return out


def yukawa_triangles():
    """A Yukawa coupling is a triangle of three lines around three dots, charges summing to zero: the Higgs for each sector is the line that closes
    the triangle of the two matter lines (EXACT): Q u^c H_u on (L, c, A2), Q d^c H_d on (L, c, B), L e^c H_d on (L, A1, B), L nu^c H_u on (L, A1, A2)."""
    V = field_vectors(); out = {}
    for name, stacks in YUKAWA.items():
        fields = name.split(); total = tuple(sum(V[f][i] for f in fields) for i in range(len(STACKS)))
        touched = {s for f in fields for s, q in zip(STACKS, V[f]) if q}
        out[name] = {"stacks": stacks, "closes": total == (0,) * len(STACKS) and touched == set(stacks), "sum_Y": sum(rep(V[f])["Y"] for f in fields)}
    return out


def z6_phase(r):
    """t/3 + d/2 + Y mod 1: the phase by which the Z6 generator (omega, -1, e^{2 pi i/6}) acts; zero iff the generator acts trivially."""
    return (Fr(r["triality"], 3) + Fr(r["duality"], 2) + r["Y"]) % 1


def charge_triality(r):
    """Electric charges of a block's components mod 1, against (2/3) x triality: equal on every Z6-trivial block."""
    t3 = (Fr(1, 2), Fr(-1, 2)) if r["weak"] == 2 else (Fr(0),)
    return {"charges_mod_1": sorted({(x + r["Y"]) % 1 for x in t3}), "two_thirds_triality": (Fr(2 * r["triality"], 3)) % 1}


def eisenstein():
    """The colour plane: weights at the cube roots of unity, roots at (1 - omega) x units, twelve directions 30 degrees apart (the roots of G2)."""
    w = complex(-0.5, math.sqrt(3) / 2)
    weights = [1, w, w * w]; anti = [-z for z in weights]
    roots = [(1 - w) * u for u in (1, -1, w, -w, w * w, -w * w)]
    dirs = sorted({round(math.degrees(math.atan2(z.imag, z.real)) % 360, 6) for z in weights + anti + roots})
    return {"weights": weights, "antiweights": anti, "roots": roots, "directions": dirs, "step_degrees": dirs[1] - dirs[0],
            "root_over_weight": abs(1 - w), "triality_quotient": "Z[omega]/(1 - omega) = Z/3", "g2_roots": len(weights + anti + roots),
            "g2_weyl_order": 12, "sm_carriers": 8 + 3 + 1}


